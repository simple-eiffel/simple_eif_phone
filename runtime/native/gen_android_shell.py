"""Writes android_shell/ from simple_shell/src: the same classes with every C call
stubbed out, so that simple_widgets compiles for Android with its interfaces intact.

Classes named in HAND_WRITTEN are left alone: they have real Android bodies.
Run after simple_shell changes. A stubbed feature does nothing and answers the default:
there is no printer, spell checker or desktop grab on the phone yet.
"""
import os, re, sys

SRC = os.path.join(os.environ.get('SIMPLE_EIFFEL', r'D:\prod'), 'simple_shell', 'src')
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', 'android_shell')
HAND_WRITTEN = {'shell_window.e'}
BANNER = '-- GENERATED by runtime/native/gen_android_shell.py from simple_shell. Do not edit.\n'


def stub(text):
    """Replaces each external body with an empty routine."""
    lines = text.replace('\r\n', '\n').split('\n')
    out, i, count = [], 0, 0
    while i < len(lines):
        line = lines[i]
        if re.match(r'^\s*external\b', line):
            indent = re.match(r'^\s*', line).group(0)
            if re.search(r'\bend\s*$', line):        # all on one line
                i += 1
            else:
                i += 1
                in_block = False
                while i < len(lines):
                    current = lines[i]
                    if '"[' in current:
                        in_block = True
                    if in_block:
                        if ']"' in current:
                            in_block = False
                    elif current.startswith(indent + 'end'):
                        break
                    i += 1
                i += 1
            out.append(indent + 'do')
            out.append(indent + 'end')
            count += 1
            continue
        out.append(line)
        i += 1
    return '\n'.join(out), count


def without_contracts(text):
    """A stub has no state behind it, so contracts about that state cannot hold."""
    out, skipping = [], False
    body_start = re.compile(r'^\t\t(do|local|once|deferred|attribute|end|external)\b')
    for line in text.split('\n'):
        if re.match(r'^\t\t(require|ensure)(\s+then|\s+else)?\s*$', line):
            skipping = True
            continue
        if skipping and body_start.match(line):
            skipping = False
        if line.startswith('invariant') or (skipping and re.match(r'^(feature|end)\b', line)):
            skipping = line.startswith('invariant')
        if not skipping:
            out.append(line)
    text = '\n'.join(out)
    if not text.rstrip().endswith('end'):
        text = text.rstrip() + '\n\nend\n'
    return text


def main():
    os.makedirs(OUT, exist_ok=True)
    total = 0
    for name in sorted(os.listdir(SRC)):
        if name.endswith('.e') and name not in HAND_WRITTEN:
            text = open(os.path.join(SRC, name), encoding='utf-8').read()
            body, count = stub(text)
            body = without_contracts(body)
            total += count
            open(os.path.join(OUT, name), 'w', encoding='utf-8', newline='\n').write(BANNER + body)
    print('stubbed', total, 'C calls')


main()
